CREATE SCHEMA IF NOT EXISTS modelo_estrela;

CREATE TABLE IF NOT EXISTS modelo_estrela.dimensao_data (
    chave_data INTEGER PRIMARY KEY,
    data DATE NOT NULL UNIQUE,
    ano SMALLINT NOT NULL,
    trimestre SMALLINT NOT NULL CHECK (trimestre BETWEEN 1 AND 4),
    mes SMALLINT NOT NULL CHECK (mes BETWEEN 1 AND 12),
    nome_mes VARCHAR(20) NOT NULL,
    dia SMALLINT NOT NULL CHECK (dia BETWEEN 1 AND 31),
    dia_da_semana SMALLINT NOT NULL CHECK (dia_da_semana BETWEEN 1 AND 7),
    nome_dia_da_semana VARCHAR(20) NOT NULL
);

CREATE TABLE IF NOT EXISTS modelo_estrela.dimensao_funcionario (
    chave_funcionario BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo_funcionario_origem INTEGER NOT NULL UNIQUE,
    primeiro_nome VARCHAR(100),
    nome_do_meio VARCHAR(100),
    sobrenome VARCHAR(100),
    titulo VARCHAR(20),
    cargo VARCHAR(100) NOT NULL,
    genero CHAR(1),
    estado_civil CHAR(1),
    salario_fixo BOOLEAN NOT NULL,
    funcionario_atual BOOLEAN NOT NULL
);

CREATE TABLE IF NOT EXISTS modelo_estrela.dimensao_departamento (
    chave_departamento BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo_departamento_origem INTEGER UNIQUE,
    nome_departamento VARCHAR(100) NOT NULL,
    grupo_departamento VARCHAR(100)
);

CREATE TABLE IF NOT EXISTS modelo_estrela.dimensao_turno (
    chave_turno BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo_turno_origem INTEGER UNIQUE,
    nome_turno VARCHAR(100) NOT NULL,
    horario_inicio TIME,
    horario_fim TIME
);

CREATE TABLE IF NOT EXISTS modelo_estrela.fato_quadro_funcionario (
    chave_registro BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo_funcionario_origem INTEGER NOT NULL UNIQUE,
    chave_funcionario BIGINT NOT NULL
        REFERENCES modelo_estrela.dimensao_funcionario (chave_funcionario),
    chave_departamento BIGINT NOT NULL
        REFERENCES modelo_estrela.dimensao_departamento (chave_departamento),
    chave_turno BIGINT NOT NULL
        REFERENCES modelo_estrela.dimensao_turno (chave_turno),
    chave_data_contratacao INTEGER NOT NULL
        REFERENCES modelo_estrela.dimensao_data (chave_data),
    funcionario_atual BOOLEAN NOT NULL,
    horas_ferias SMALLINT NOT NULL,
    horas_afastamento SMALLINT NOT NULL,
    taxa_remuneracao_atual NUMERIC(19, 4),
    frequencia_pagamento_atual SMALLINT
);

CREATE TABLE IF NOT EXISTS modelo_estrela.fato_historico_remuneracao (
    chave_evento BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo_funcionario_origem INTEGER NOT NULL,
    chave_funcionario BIGINT NOT NULL
        REFERENCES modelo_estrela.dimensao_funcionario (chave_funcionario),
    chave_data_alteracao INTEGER NOT NULL
        REFERENCES modelo_estrela.dimensao_data (chave_data),
    data_alteracao TIMESTAMP NOT NULL,
    taxa_remuneracao NUMERIC(19, 4) NOT NULL CHECK (taxa_remuneracao >= 0),
    frequencia_pagamento SMALLINT NOT NULL,
    UNIQUE (codigo_funcionario_origem, data_alteracao)
);

CREATE TABLE IF NOT EXISTS modelo_estrela.controle_incremental_recursos_humanos (
    tabela_origem VARCHAR(100) PRIMARY KEY,
    ultima_modificacao TIMESTAMP NOT NULL,
    atualizado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS indice_quadro_funcionario_departamento
    ON modelo_estrela.fato_quadro_funcionario (chave_departamento);
CREATE INDEX IF NOT EXISTS indice_quadro_funcionario_turno
    ON modelo_estrela.fato_quadro_funcionario (chave_turno);
CREATE INDEX IF NOT EXISTS indice_quadro_funcionario_data_contratacao
    ON modelo_estrela.fato_quadro_funcionario (chave_data_contratacao);
CREATE INDEX IF NOT EXISTS indice_historico_remuneracao_funcionario
    ON modelo_estrela.fato_historico_remuneracao (chave_funcionario);
CREATE INDEX IF NOT EXISTS indice_historico_remuneracao_data
    ON modelo_estrela.fato_historico_remuneracao (chave_data_alteracao);

